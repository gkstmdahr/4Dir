_CACHE = {}


def tip_for(text, labels=None):
    """메뉴 글자 → 설명 ('' 없으면). labels = {기능 id: 이름} (keymap.LABEL)"""
    t = text.split("\t")[0].replace("&", "").strip()
    if not t:
        return ""
    if "pairs" not in _CACHE:
        d = by_action()
        pairs = []
        pre = [T("설정: {0}").format(""), T("표시: {0}").format("")]   # 기능 이름 앞 분류 글자는 메뉴엔 없음
        for a, lbl in (labels or {}).items():
            if a in d:
                for x in pre:
                    if lbl.startswith(x):
                        lbl = lbl[len(x):]
                pairs.append((lbl.rstrip("…").strip(), d[a]))
        pairs += menu_tips()
        pairs.sort(key=lambda x: -len(x[0]))   # 긴 이름부터 (짧은 이름이 먼저 걸리지 않게)
        _CACHE["pairs"] = pairs
    for k, v in _CACHE["pairs"]:
        if k and t.startswith(k):
            return v
    return ""
